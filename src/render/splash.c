#include "splash.h"

/* Timeline (seconds):
 *      libdragon logo                 Cydonis logo
 *  |- drop/spin/fade -|- hold -|- xfade -|-- hold --|- fade to title -|
 *  0                2.2      3.2       4.6        14.0             16.4
 * The Cydonis phases sum to ~13.2s so the authored jingle plays out
 * exactly once, ending as the title scene takes over. */
#define T_LD_IN    2.2f
#define T_LD_HOLD  3.2f
#define T_XFADE    4.6f
#define T_CYD_HOLD 14.0f
#define T_END      16.4f

#define SCREEN_W 320
#define SCREEN_H 240

/* Splash audio borrows the wav64 music channels (music.c CH_WAV 0..1);
 * music doesn't start until the title screen, so there's no contest. */
#define CH_SPLASH 0

static sprite_t *ld_spr, *cyd_spr;
static wav64_t   sfx_dragon, sfx_jingle;

/* The sine-wave pass rewrites a full surface on the CPU each frame, so it
 * needs the same double-buffer + syncpoint discipline as the tunnel verts
 * (3 framebuffers let the CPU run 2 frames ahead of the RDP). */
static surface_t        wave_buf[2];
static rspq_syncpoint_t buf_sync[2];
static int              flip;

static float t;
static bool  skipped, dragon_started, jingle_started;

void splash_init(void) {
    ld_spr  = sprite_load("rom:/ld_logo.sprite");
    cyd_spr = sprite_load("rom:/cydonis.sprite");
    wav64_open(&sfx_dragon, "rom:/dragon.wav64");
    wav64_open(&sfx_jingle, "rom:/jingle.wav64");

    surface_t px = sprite_get_pixels(cyd_spr);
    wave_buf[0] = surface_alloc(FMT_RGBA16, px.width, px.height);
    wave_buf[1] = surface_alloc(FMT_RGBA16, px.width, px.height);
}

void splash_update(float dt) {
    if (splash_finished()) return;
    if (!dragon_started) {
        dragon_started = true;
        wav64_play(&sfx_dragon, CH_SPLASH);
    }
    t += dt;
    if (!jingle_started && t >= T_LD_HOLD) {
        jingle_started = true;
        mixer_ch_stop(CH_SPLASH);
        mixer_ch_stop(CH_SPLASH + 1);
        wav64_play(&sfx_jingle, CH_SPLASH);
    }
}

void splash_skip(void) {
    skipped = true;
    mixer_ch_stop(CH_SPLASH);
    mixer_ch_stop(CH_SPLASH + 1);
}

bool splash_fullscreen(void) { return !skipped && t < T_CYD_HOLD; }
bool splash_finished(void)   { return skipped || t >= T_END; }

static void logo_modes(float alpha) {
    int a = (int)(alpha * 255.f);
    if (a < 0) a = 0;
    if (a > 255) a = 255;
    rdpq_set_mode_standard();
    rdpq_mode_combiner(RDPQ_COMBINER_TEX_FLAT);
    rdpq_mode_blender(RDPQ_BLENDER_MULTIPLY);
    rdpq_mode_filter(FILTER_BILINEAR);
    rdpq_set_prim_color(RGBA32(255, 255, 255, a));
}

static void draw_ld(float alpha, float theta, float ycenter) {
    logo_modes(alpha);
    rdpq_blitparms_t p = {
        .cx = ld_spr->width / 2,
        .cy = ld_spr->height / 2,
        .theta = theta,
        .filtering = true,
    };
    rdpq_sprite_blit(ld_spr, SCREEN_W / 2.f, ycenter, &p);
}

/* Cydonis logo with each pixel column displaced by a travelling sine.
 * Done CPU-side into wave_buf (one row-major pass over ~55k texels) and
 * blitted once — far cheaper for the RDP than 320 one-texel-wide loads. */
static void draw_cyd(float alpha, float amp, float wt) {
    surface_t px = sprite_get_pixels(cyd_spr);
    int W = px.width, H = px.height;
    if (W > SCREEN_W) W = SCREEN_W;
    float x0 = (SCREEN_W - W) / 2.f;
    float y0 = (SCREEN_H - H) / 2.f;

    logo_modes(alpha);

    if (amp < 0.25f) {   /* flat during the hold: blit the sprite as-is */
        rdpq_sprite_blit(cyd_spr, x0, y0, NULL);
        return;
    }

    surface_t      *dst = &wave_buf[flip];
    const uint16_t *s   = px.buffer;
    uint16_t       *d   = dst->buffer;
    int sp = px.stride / 2, dp = dst->stride / 2;

    static int16_t off[SCREEN_W];
    for (int x = 0; x < W; x++)
        off[x] = (int16_t)(amp * fm_sinf(x * 0.049f + wt * 4.2f));

    for (int y = 0; y < H; y++) {
        uint16_t *row = d + y * dp;
        for (int x = 0; x < W; x++) {
            int sy = y - off[x];
            /* vacated texels go transparent (RGBA16 zero) */
            row[x] = ((unsigned)sy < (unsigned)H) ? s[sy * sp + x] : 0;
        }
    }
    data_cache_hit_writeback(d, dst->stride * H);
    rdpq_tex_blit(dst, x0, y0, NULL);
}

static float ease(float u) { return u * u * (3.f - 2.f * u); }

void splash_render(surface_t *disp) {
    flip ^= 1;
    if (buf_sync[flip])
        rspq_syncpoint_wait(buf_sync[flip]);

    rdpq_attach(disp, NULL);
    rdpq_set_mode_fill(RGBA32(0, 0, 0, 255));
    rdpq_fill_rectangle(0, 0, SCREEN_W, SCREEN_H);

    if (t < T_LD_IN) {
        /* Crossfade in while dropping from above the screen, unwinding
         * one full turn as it settles. */
        float e = ease(t / T_LD_IN);
        draw_ld(t / T_LD_IN, 6.2831853f * (1.f - e), -140.f + e * 260.f);
    } else if (t < T_LD_HOLD) {
        draw_ld(1.f, 0.f, 120.f);
    } else if (t < T_XFADE) {
        float u = (t - T_LD_HOLD) / (T_XFADE - T_LD_HOLD);
        draw_ld(1.f - u, 0.f, 120.f);
        draw_cyd(u, 2.f + 6.f * (1.f - u), t);
    } else {
        /* Hold: gentle residual ripple while the jingle plays. */
        draw_cyd(1.f, 2.f, t);
    }

    rdpq_detach_show();
    buf_sync[flip] = rspq_syncpoint_new();
}

void splash_draw_overlay(void) {
    if (skipped || t < T_CYD_HOLD || t >= T_END) return;

    flip ^= 1;
    /* One-time drain of the fullscreen-phase syncpoints; after that the
     * frame-start wait in render.c retires frame N-2 (which is the last
     * reader of this wave buffer) before we get here. */
    if (buf_sync[flip]) {
        rspq_syncpoint_wait(buf_sync[flip]);
        buf_sync[flip] = 0;
    }

    float u = (t - T_CYD_HOLD) / (T_END - T_CYD_HOLD);

    /* Black veil fading away so the whole screen, not just the logo,
     * crossfades from the splash into the live title scene. */
    rdpq_set_mode_standard();
    rdpq_mode_combiner(RDPQ_COMBINER_FLAT);
    rdpq_mode_blender(RDPQ_BLENDER_MULTIPLY);
    rdpq_set_prim_color(RGBA32(0, 0, 0, (int)((1.f - u) * 255.f)));
    rdpq_fill_rectangle(0, 0, SCREEN_W, SCREEN_H);

    draw_cyd(1.f - u, 2.f + 6.f * u, t);
}
