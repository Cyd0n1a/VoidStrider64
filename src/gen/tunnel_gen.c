#include "tunnel_gen.h"
#include "palette_gen.h"
#include "../meta/options.h"
#include <libdragon.h>
#include <math.h>

#define TUNNEL_BEND     34.f    /* max sideways drift of ring centers */
#define BASE_SPEED      240.f   /* flight speed (units/sec) at intensity 0 */

/* Per-ring shape parameters: an organic polygon built from two summed
 * sine harmonics on top of a base radius (GDD 6.1 — cheap Perlin stand-in). */
typedef struct {
    float base_r;
    float amp[2];
    int   k[2];             /* harmonic counts around the ring */
    float phase[2];
    float phase_spd[2];
    float hue_off;
} ring_t;

static ring_t   rings[TUNNEL_RINGS];
static int      head;          /* circular-buffer index of the nearest ring */
static uint32_t head_abs;      /* absolute ring counter, drives bend path */
static float    scroll;        /* [0, TUNNEL_DZ) travel since last recycle */
static float    roll;
static float    intensity_cur;
static uint32_t rng_state;

static float costab[TUNNEL_SIDES], sintab[TUNNEL_SIDES];

/* ---- Seeded RNG (xorshift32) so runs are reproducible (GDD 8.3) ---- */
static uint32_t rng(void) {
    rng_state ^= rng_state << 13;
    rng_state ^= rng_state >> 17;
    rng_state ^= rng_state << 5;
    return rng_state;
}
static float frand(void) { return (float)(rng() >> 8) / 16777216.f; }
static float frange(float a, float b) { return a + frand() * (b - a); }

static void ring_gen(ring_t *r) {
    r->base_r       = frange(115.f, 165.f);
    r->amp[0]       = frange(10.f, 26.f);
    r->k[0]         = 2 + (int)(rng() % 3);
    r->amp[1]       = frange(4.f, 12.f);
    r->k[1]         = 5 + (int)(rng() % 3);
    for (int i = 0; i < 2; i++) {
        r->phase[i]     = frange(0.f, 6.2831853f);
        r->phase_spd[i] = frange(0.5f, 1.6f) * ((rng() & 1) ? 1.f : -1.f);
    }
    r->hue_off      = frange(-0.05f, 0.05f);
}

void tunnel_init(uint32_t seed) {
    rng_state = seed ? seed : 1;
    head      = 0;
    head_abs  = 0;
    scroll    = 0.f;
    roll      = 0.f;
    intensity_cur = 0.f;

    for (int j = 0; j < TUNNEL_SIDES; j++) {
        float th = 6.2831853f * (float)j / TUNNEL_SIDES;
        costab[j] = fm_cosf(th);
        sintab[j] = fm_sinf(th);
    }
    for (int i = 0; i < TUNNEL_RINGS; i++)
        ring_gen(&rings[i]);
}

void tunnel_update(float dt, float intensity) {
    /* Ease toward the requested intensity so lulls/spikes feel musical,
     * not stepped (GDD 6.2). */
    float blend = dt * 3.f;
    if (blend > 1.f) blend = 1.f;
    intensity_cur += (intensity - intensity_cur) * blend;

    /* Background Intensity option scales turbulence and roll (GDD 8.4). */
    float bg   = g_options.bg_intensity;
    float turb = (1.f + 1.5f * intensity_cur) * (0.35f + 0.65f * bg);
    for (int i = 0; i < TUNNEL_RINGS; i++) {
        rings[i].phase[0] += rings[i].phase_spd[0] * turb * dt;
        rings[i].phase[1] += rings[i].phase_spd[1] * turb * dt;
    }

    roll += dt * (0.12f + 0.5f * intensity_cur) * (0.4f + 0.6f * bg);
    if (roll > 6.2831853f) roll -= 6.2831853f;

    scroll += BASE_SPEED * (0.75f + 1.05f * intensity_cur) * dt;

    /* Conveyor-belt recycle: nearest ring passes the camera, becomes the
     * new farthest ring with fresh parameters (GDD 6.1). */
    while (scroll >= TUNNEL_DZ) {
        scroll -= TUNNEL_DZ;
        ring_gen(&rings[head]);
        head = (head + 1) % TUNNEL_RINGS;
        head_abs++;
    }
}

float tunnel_roll(void) { return roll; }

void tunnel_build_verts(T3DVertPacked *dst, float time, int n_rings) {
    float base_hue = palette_base_hue(time);
    float inv_span = 1.f / (float)(TUNNEL_RINGS - 1);
    float recycle_t = scroll / TUNNEL_DZ;
    /* Background Intensity option dims/desaturates the tunnel (GDD 8.4). */
    float bg_v = 0.62f * (0.5f + 0.5f * g_options.bg_intensity);
    float bg_s = 0.68f * (0.72f + 0.28f * g_options.bg_intensity);
    int   idx = 0;

    for (int i = 0; i < n_rings; i++) {
        const ring_t *rg = &rings[(head + i) % TUNNEL_RINGS];
        uint32_t abs_i = head_abs + i;
        float z  = TUNNEL_NEAR_Z - (float)i * TUNNEL_DZ + scroll;

        /* Ring centers wander smoothly with absolute index so the tube
         * snakes rather than staying a straight pipe. */
        float cx = TUNNEL_BEND * fm_sinf((float)abs_i * 0.13f);
        float cy = TUNNEL_BEND * fm_sinf((float)abs_i * 0.09f + 1.7f);

        /* Depth cue: recede into darkness (GDD 5.4 fog-as-vertex-color). */
        float depth  = 1.f - (float)i * inv_span;
        float bright = depth * depth;
        if (i == 0)                 bright *= 1.f - recycle_t;  /* fade out */
        if (i == TUNNEL_RINGS - 1)  bright *= recycle_t;        /* fade in  */

        float pulse = 0.8f + 0.2f * fm_sinf(time * 2.2f + (float)abs_i * 0.9f);
        float hue   = base_hue + (float)i * 0.018f + rg->hue_off;

        for (int j = 0; j < TUNNEL_SIDES; j += 2) {
            int16_t  px[2], py[2];
            uint32_t col[2];
            for (int s = 0; s < 2; s++) {
                float th = 6.2831853f * (float)(j + s) / TUNNEL_SIDES;
                float r  = rg->base_r
                         + rg->amp[0] * fm_sinf((float)rg->k[0] * th + rg->phase[0])
                         + rg->amp[1] * fm_sinf((float)rg->k[1] * th + rg->phase[1]);
                /* Flowing energy bands around the wall keep it alive without
                 * textures; kept dim so gameplay reads on top (GDD 1.1 #3). */
                float band = 0.78f + 0.22f * fm_sinf(3.f * th + time * 2.6f + (float)i * 0.55f);
                float v = bg_v * bright * pulse * band;
                col[s] = palette_hsv_rgba(hue, bg_s, v);
                px[s]  = (int16_t)(cx + costab[j + s] * r);
                py[s]  = (int16_t)(cy + sintab[j + s] * r);
            }
            dst[idx++] = (T3DVertPacked){
                .posA = { px[0], py[0], (int16_t)z }, .normA = 0, .rgbaA = col[0], .stA = {0, 0},
                .posB = { px[1], py[1], (int16_t)z }, .normB = 0, .rgbaB = col[1], .stB = {0, 0},
            };
        }
    }
}
