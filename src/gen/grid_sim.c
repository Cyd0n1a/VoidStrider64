#include "grid_sim.h"
#include "palette_gen.h"
#include "../sim/arena.h"
#include <libdragon.h>
#include <math.h>

/* Critically-damped spring per intersection (GDD 6.3): omega = 2*pi*f. */
#define SPRING_OMEGA  15.7f    /* ~2.5 Hz snap-back */
#define OFFSET_MAX    48.f

#define CELL_W  (2.f * ARENA_HALF_W / GRID_COLS)
#define CELL_H  (2.f * ARENA_HALF_H / GRID_ROWS)

static float off[GRID_IX_H][GRID_IX_W];
static float vel[GRID_IX_H][GRID_IX_W];

void grid_init(void) {
    for (int r = 0; r < GRID_IX_H; r++)
        for (int c = 0; c < GRID_IX_W; c++)
            off[r][c] = vel[r][c] = 0.f;
}

void grid_update(float dt) {
    for (int r = 0; r < GRID_IX_H; r++) {
        for (int c = 0; c < GRID_IX_W; c++) {
            float acc = -SPRING_OMEGA * SPRING_OMEGA * off[r][c]
                        - 2.f * SPRING_OMEGA * vel[r][c];
            vel[r][c] += acc * dt;
            off[r][c] += vel[r][c] * dt;
            if (off[r][c] >  OFFSET_MAX) off[r][c] =  OFFSET_MAX;
            if (off[r][c] < -OFFSET_MAX) off[r][c] = -OFFSET_MAX;
        }
    }
}

void grid_impulse(float x, float y, float strength, float radius) {
    float inv_r = 1.f / radius;
    for (int r = 0; r < GRID_IX_H; r++) {
        float gy = -ARENA_HALF_H + (float)r * CELL_H;
        for (int c = 0; c < GRID_IX_W; c++) {
            float gx = -ARENA_HALF_W + (float)c * CELL_W;
            float dx = gx - x, dy = gy - y;
            float d2 = dx * dx + dy * dy;
            if (d2 >= radius * radius) continue;
            float fall = 1.f - sqrtf(d2) * inv_r;
            vel[r][c] -= strength * fall;   /* push away from camera (-Z) */
        }
    }
}

/* Pack one vertex into the A or B half of a packed pair. */
static inline void put_vert(T3DVertPacked *dst, int slot,
                            float x, float y, float z, uint32_t col) {
    T3DVertPacked *p = &dst[slot / 2];
    if (slot & 1) {
        p->posB[0] = (int16_t)x; p->posB[1] = (int16_t)y; p->posB[2] = (int16_t)z;
        p->normB = 0; p->rgbaB = col; p->stB[0] = 0; p->stB[1] = 0;
    } else {
        p->posA[0] = (int16_t)x; p->posA[1] = (int16_t)y; p->posA[2] = (int16_t)z;
        p->normA = 0; p->rgbaA = col; p->stA[0] = 0; p->stA[1] = 0;
    }
}

void grid_build_verts(T3DVertPacked *dst, float time, float beat) {
    /* Grid hue rides the same wheel walk as the tunnel, offset so the
     * board stays distinguishable as the palette drifts (GDD 5.3).
     * Brightness breathes gently on its own and flashes with the
     * music's detected beats (GDD 6.3). */
    float hue   = palette_base_hue(time) + 0.45f;
    float pulse = 0.06f * fm_sinf(time * 3.f) + beat * 0.15f;

    for (int r = 0; r < GRID_ROWS; r++) {
        T3DVertPacked *batch = dst + r * GRID_PACKED_PER_BATCH;
        int slot = 0;

        for (int rr = r; rr <= r + 1; rr++) {
            float gy = -ARENA_HALF_H + (float)rr * CELL_H;
            for (int c = 0; c < GRID_IX_W; c++) {
                float gx = -ARENA_HALF_W + (float)c * CELL_W;
                float o  = off[rr][c];
                /* Displaced verts glow brighter, GW-style energy look. */
                float glow = o < 0.f ? -o : o;
                glow = glow * 0.022f;
                if (glow > 0.45f) glow = 0.45f;
                float v = 0.42f + glow + pulse;
                uint32_t col = palette_hsv_rgba(hue, 0.5f, v);
                uint32_t a   = 150 + (uint32_t)((glow + beat * 0.16f) * 230.f);
                if (a > 255) a = 255;
                col = (col & 0xFFFFFF00u) | a;
                put_vert(batch, slot++, gx, gy, ARENA_Z + o, col);
            }
        }

        /* Cell centers: nearly invisible membrane interior (GDD 6.3). */
        float gy = -ARENA_HALF_H + ((float)r + 0.5f) * CELL_H;
        uint32_t ccol = (palette_hsv_rgba(hue, 0.5f, 0.10f) & 0xFFFFFF00u) | 30;
        for (int c = 0; c < GRID_COLS; c++) {
            float gx = -ARENA_HALF_W + ((float)c + 0.5f) * CELL_W;
            float o = (off[r][c] + off[r][c + 1] +
                       off[r + 1][c] + off[r + 1][c + 1]) * 0.25f * 0.85f;
            put_vert(batch, slot++, gx, gy, ARENA_Z + o, ccol);
        }
    }
}
