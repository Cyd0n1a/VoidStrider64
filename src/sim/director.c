#include "director.h"
#include "arena.h"
#include "enemies.h"
#include "../meta/scoring.h"
#include <math.h>

#define SPAWN_MIN_DIST 100.f   /* never spawn in the player's face */

/* Species unlock schedule + spawn weights (GDD 3.6: difficulty scales
 * continuously with elapsed time; GDD 3.1: Snake is late-game). */
typedef struct {
    species_t sp;
    float     unlock_t;    /* seconds into the run */
    float     weight;
    int       max_alive;   /* 0 = uncapped */
} wave_def_t;

static const wave_def_t WAVES[] = {
    { SP_WANDERER,   0.f, 1.00f, 0 },
    { SP_SEEKER,    25.f, 0.75f, 0 },
    { SP_SWARMER,   50.f, 0.45f, 0 },   /* spawns a whole pack */
    { SP_TURRET,    80.f, 0.35f, 2 },
    { SP_PULSAR,   110.f, 0.40f, 3 },
};
#define WAVE_COUNT (int)(sizeof(WAVES) / sizeof(WAVES[0]))

#define SNAKE_UNLOCK   150.f
#define SNAKE_PERIOD   45.f
#define SNAKE_SEGMENTS 7

static float    elapsed;
static float    spawn_timer;
static float    snake_timer;
static uint32_t rng_state;

static uint32_t rng(void) {
    rng_state ^= rng_state << 13;
    rng_state ^= rng_state >> 17;
    rng_state ^= rng_state << 5;
    return rng_state;
}
static float frange(float a, float b) {
    return a + ((float)(rng() >> 8) / 16777216.f) * (b - a);
}

void director_init(uint32_t seed) {
    rng_state   = seed ? seed : 1;
    elapsed     = 0.f;
    spawn_timer = 1.2f;
    snake_timer = 0.f;
}

static bool edge_point(float px, float py, float *ox, float *oy) {
    for (int try = 0; try < 6; try++) {
        int   edge = (int)(rng() & 3);
        float x, y;
        switch (edge) {
            case 0:  x = -ARENA_HALF_W + 14.f; y = frange(-ARENA_HALF_H, ARENA_HALF_H); break;
            case 1:  x =  ARENA_HALF_W - 14.f; y = frange(-ARENA_HALF_H, ARENA_HALF_H); break;
            case 2:  y = -ARENA_HALF_H + 14.f; x = frange(-ARENA_HALF_W, ARENA_HALF_W); break;
            default: y =  ARENA_HALF_H - 14.f; x = frange(-ARENA_HALF_W, ARENA_HALF_W); break;
        }
        float dx = x - px, dy = y - py;
        if (dx * dx + dy * dy < SPAWN_MIN_DIST * SPAWN_MIN_DIST) continue;
        *ox = x; *oy = y;
        return true;
    }
    return false;
}

static void spawn_pick(float px, float py) {
    float x, y;
    if (!edge_point(px, py, &x, &y)) return;

    /* Weighted pick among unlocked species. */
    float total = 0.f;
    for (int w = 0; w < WAVE_COUNT; w++) {
        if (elapsed < WAVES[w].unlock_t) continue;
        if (WAVES[w].max_alive &&
            enemies_count_species(WAVES[w].sp) >= WAVES[w].max_alive) continue;
        total += WAVES[w].weight;
    }
    if (total <= 0.f) return;

    float roll = frange(0.f, total);
    for (int w = 0; w < WAVE_COUNT; w++) {
        if (elapsed < WAVES[w].unlock_t) continue;
        if (WAVES[w].max_alive &&
            enemies_count_species(WAVES[w].sp) >= WAVES[w].max_alive) continue;
        roll -= WAVES[w].weight;
        if (roll > 0.f) continue;

        if (WAVES[w].sp == SP_SWARMER) {
            /* Packs of 6-8 (GDD 3.1), scattered around the edge point. */
            int pack = 6 + (int)(rng() % 3);
            for (int p = 0; p < pack; p++)
                enemies_spawn(x + frange(-24.f, 24.f), y + frange(-24.f, 24.f),
                              SP_SWARMER, 0);
        } else {
            enemies_spawn(x, y, WAVES[w].sp, 0);
        }
        return;
    }
}

void director_update(float dt, float px, float py) {
    elapsed += dt;

    /* Spawn interval 2.4s -> 0.8s over ~1 minute; alive cap rises with
     * time but always leaves pool room for splits and snake segments. */
    float interval = 2.4f - elapsed * 0.027f;
    if (interval < 0.8f) interval = 0.8f;

    int cap = 8 + (int)(elapsed / 10.f);
    if (cap > 30) cap = 30;

    spawn_timer -= dt;
    if (spawn_timer <= 0.f) {
        spawn_timer += interval;
        if (enemies_count() < cap)
            spawn_pick(px, py);
    }

    /* Snake: late-game set-piece, one at a time (GDD 3.1). */
    if (elapsed >= SNAKE_UNLOCK) {
        snake_timer -= dt;
        if (snake_timer <= 0.f && enemies_count_species(SP_SNAKE) == 0) {
            float x, y;
            if (edge_point(px, py, &x, &y))
                enemies_spawn_snake(x, y, SNAKE_SEGMENTS);
            snake_timer = SNAKE_PERIOD;
        }
    }
}

float director_intensity(void) {
    float i = (float)enemies_count() / 18.f + scoring_kill_pulse();
    return i > 1.f ? 1.f : i;
}
